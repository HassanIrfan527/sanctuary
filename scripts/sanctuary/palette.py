#!/usr/bin/env python3
"""Signal's palettes → the outside apps' files.

    palette.py build     write every palette's kitty / niri / starship file
    palette.py words     list the palette words, in picker order

palettes/signal.json is the one source. Quickshell reads it live (Theme.qml);
the apps can't, so `build` writes one small file per palette per app, and
palette.sh only re-points a symlink at switch time — nothing is written then.
Run `build` after editing the JSON; the files it writes are committed.

    kitty/kitty/palettes/<word>.conf       included by style-signal.conf (palette.conf link)
    niri/niri/palettes/<word>.kdl          included by config.kdl after layout.kdl (palette.kdl link)
    niri/niri/palettes/none.kdl            what palette.kdl points at outside Signal
    starship/themes/signal/<word>.toml     signal.toml with its [palettes.signal] table swapped
"""
import json
import re
import sys
from pathlib import Path

DOT = Path.home() / ".dotfiles"
SRC = DOT / "palettes" / "signal.json"
KITTY = DOT / "kitty" / "kitty" / "palettes"
NIRI = DOT / "niri" / "niri" / "palettes"
STAR = DOT / "starship" / "themes"
HEAD = "generated by scripts/sanctuary/palette.py build from palettes/signal.json — edit that, not this"


def load():
    return json.loads(SRC.read_text())["palettes"]


def kitty(p):
    a = p["ansi"]
    lines = [
        f"# {p['name']} — {HEAD}",
        f"background {p['crust']}",
        f"foreground {p['text']}",
        f"selection_background {p['surface0']}",
        f"cursor {p['hot']}",
        f"cursor_text_color {p['crust']}",
        f"url_color {p['link']}",
        f"active_border_color {p['hot']}",       # tab_bar.py reads HOT from here
        f"inactive_border_color {p['surface0']}",
        f"bell_border_color {p['alarm']}",
        f"active_tab_foreground {p['text']}",
        f"active_tab_background {p['crust']}",
        f"inactive_tab_foreground {p['overlay0']}",
        f"inactive_tab_background {p['crust']}",
        f"mark1_background {p['hot']}",
        f"mark1_foreground {p['crust']}",
        f"mark2_background {p['warn']}",
        f"mark2_foreground {p['crust']}",
        f"mark3_background {p['link']}",
        f"mark3_foreground {p['crust']}",
    ] + [f"color{i} {c}" for i, c in enumerate(a)]
    if p.get("fx") == "full":   # kitty.conf already has a short trail; full makes it a longer neon streak
        lines += [f"cursor_trail_color {p['hot']}", "cursor_trail_decay 0.15 0.6"]
    return "\n".join(lines) + "\n"


def alpha(hexc, a):
    """#rrggbb + an alpha 0..1 → #rrggbbaa (niri takes that)."""
    return f"{hexc}{max(0, min(255, round(a * 255))):02x}"


def niri(p):
    fx, g = p.get("fx", "off"), float(p.get("glow", 0))
    border = (f"        active-gradient from=\"{p['hot']}\" to=\"{p.get('edge', p['hot'])}\" angle=135\n"
              if fx != "off" else f"        active-color \"{p['hot']}\"\n")
    # The glow: niri's shadow, centred and tinted — a neon tube behind the focused window.
    shadow = ("    shadow {\n        on\n"
              f"        softness {round(16 + 24 * g)}\n"
              f"        spread {round(1 + 5 * g)}\n"
              "        offset x=0 y=0\n"
              "        draw-behind-window true\n"
              f"        color \"{alpha(p['hot'], 0.35 + 0.4 * g)}\"\n"
              "        inactive-color \"#00000000\"\n"
              "    }\n") if fx != "off" else ""
    return (f"// {p['name']} — {HEAD}\n"
            "// Merged over layout-signal.kdl: only the colours (and, with effects, the glow); the shape stays.\n"
            "layout {\n    border {\n" + border +
            f"        inactive-color \"{p['surface0']}\"\n"
            "    }\n" + shadow + "}\n"
            f"overview {{\n    backdrop-color \"{p['base']}\"\n}}\n")


STAR_KEYS = ["surface0", "surface2", "overlay0", "subtext0", "text", "hot", "ok", "warn", "alarm", "link"]


def starship(p, template):
    table = f"[palettes.signal]          # {p['name']} — {HEAD}\n" + \
        "".join(f"{k} = '{p[k]}'\n" for k in STAR_KEYS) + "\n"
    out, n = re.subn(r"\[palettes\.signal\].*?(?=# ── the rule between)", lambda _: table, template, flags=re.S)
    if n != 1:
        sys.exit("palette.py: signal.toml has no [palettes.signal] table to swap")
    return out


def build():
    pals = load()
    template = (STAR / "signal.toml").read_text()
    for d in (KITTY, NIRI, STAR / "signal"):
        d.mkdir(parents=True, exist_ok=True)
    (NIRI / "none.kdl").write_text(f"// No palette — {HEAD}\n// palette.kdl points here outside Signal, so the style's own layout colours stand.\n")
    for p in pals:
        w = p["word"]
        (KITTY / f"{w}.conf").write_text(kitty(p))
        (NIRI / f"{w}.kdl").write_text(niri(p))
        (STAR / "signal" / f"{w}.toml").write_text(starship(p, template))
    print(f"built {len(pals)} palettes: " + " ".join(p["word"] for p in pals))


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    if cmd == "build":
        build()
    elif cmd == "words":
        print("\n".join(p["word"] for p in load()))
    else:
        sys.exit("usage: palette.py build|words")
